async function sfx() {
  const out = path.join(ROOT, 'assets/sfx');
  fs.mkdirSync(out, { recursive: true });
  for (const [id, dur, prompt] of SFX) {
    const f = path.join(out, `${id}.mp3`);
    if (fs.existsSync(f)) { console.log(id, 'exists'); continue; }
    const r = await fetch(`${API}/v1/sound-generation?output_format=mp3_44100_128`, {
      method: 'POST', headers: H, body: JSON.stringify({ text: prompt, duration_seconds: dur, prompt_influence: 0.6 }),
    });
    if (!r.ok) { console.log(id, 'FAILED', r.status, (await r.text()).slice(0, 160)); continue; }
    fs.writeFileSync(f, Buffer.from(await r.arrayBuffer()));
    console.log(id, 'ok');
  }
}

async function music() {
  const beds = [
    ['bed-a', 'Warm hopeful cinematic film score underscore: soft felt piano melody over a warm string pad, a gentle low heartbeat pulse, slowly building to an emotional uplifting resolve. No vocals. High quality, polished.'],
    ['bed-b', 'Uplifting inspiring ambient brand film music: airy synth pads, delicate plucked arpeggio, soft piano, warm cinematic swells building to a hopeful major resolve. No drums, no vocals. Polished and premium.'],
  ];
  for (const [id, prompt] of beds) {
    for (const dur of [30, 22]) {
      const r = await fetch(`${API}/v1/sound-generation?output_format=mp3_44100_128`, {
        method: 'POST', headers: H, body: JSON.stringify({ text: prompt, duration_seconds: dur, prompt_influence: 0.45 }),
      });
      if (!r.ok) { console.log(id, dur, 'FAILED', r.status, (await r.text()).slice(0, 160)); continue; }
      fs.writeFileSync(path.join(ROOT, `assets/audio/${id}.mp3`), Buffer.from(await r.arrayBuffer()));
      console.log(id, dur, 'ok');
      break;
    }
  }
}

const [cmd, ...rest] = process.argv.slice(2);
await ({ vo, sfx, music }[cmd] ?? (() => console.log('usage: vo [ids...] | sfx | music')))(rest);
