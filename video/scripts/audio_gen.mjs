// Generates the film's sound on ElevenLabs (free tier): voiceover with word timings,
// the sound-design palette, and music-bed candidates. Reads ELEVENLABS_API_KEY from .env.
//
//   node scripts/audio_gen.mjs vo       -> assets/audio/vo/*.mp3 + assets/audio/words.js
//   node scripts/audio_gen.mjs vo vo6   -> only vo6 (the other lines' audio and timings are kept)
//   node scripts/audio_gen.mjs sfx      -> assets/sfx/*.mp3        (skips files that exist)
//   node scripts/audio_gen.mjs music    -> assets/audio/bed-*.mp3
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const env = Object.fromEntries(fs.readFileSync(path.join(ROOT, '.env'), 'utf8').split(/\r?\n/).filter((l) => l.includes('='))
  .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]));
const H = { 'xi-api-key': env.ELEVENLABS_API_KEY, 'Content-Type': 'application/json' };
const API = 'https://api.elevenlabs.io';
const ctx = { globalThis: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'timing.js'), 'utf8'), ctx);
const T = ctx.globalThis.HERCOVA_TIMING;

// Matilda — "Knowledgable, Professional", upbeat American (ElevenLabs premade, free plan), on the v3 model.
// Chosen by ear from renders/voice-samples (2026-09-29); the previous voice was Lily (pFZP5JQG7iQjIQuC4Bku).
const VOICE = 'XrExE9yKIg1WjnnlVkGX';
const MODEL = 'eleven_v3';

function toWords(al) {
  const words = [];
  let cur = null;
  for (let i = 0; i < al.characters.length; i++) {
    const ch = al.characters[i];
    if (/\s/.test(ch)) { if (cur) { words.push(cur); cur = null; } continue; }
    if (!cur) cur = [ '', +al.character_start_times_seconds[i].toFixed(3), 0 ];
    cur[0] += ch;
    cur[2] = +al.character_end_times_seconds[i].toFixed(3);
  }
  if (cur) words.push(cur);
  return words;
}

async function vo(only = []) {
  const out = path.join(ROOT, 'assets/audio/vo');
  fs.mkdirSync(out, { recursive: true });
  // regenerate only the named lines (e.g. `vo vo6`), keeping every other line's audio and timings
  const words = {};
  const prev = path.join(ROOT, 'assets/audio/words.js');
  if (only.length && fs.existsSync(prev)) {
    const c = { globalThis: {} };
    vm.runInNewContext(fs.readFileSync(prev, 'utf8'), c);
    Object.assign(words, c.globalThis.HERCOVA_WORDS);
  }
  for (const line of T.vo) {
    if (only.length && !only.includes(line.id)) continue;
    const r = await fetch(`${API}/v1/text-to-speech/${VOICE}/with-timestamps?output_format=mp3_44100_128`, {
      method: 'POST', headers: H,
      body: JSON.stringify({ text: line.text, model_id: MODEL, voice_settings: { stability: 0.5, similarity_boost: 0.8, style: 0.3, use_speaker_boost: true } }),
    });
    const j = await r.json();
    if (!r.ok) throw new Error(`${line.id}: ${r.status} ${JSON.stringify(j).slice(0, 200)}`);
    fs.writeFileSync(path.join(out, `${line.id}.mp3`), Buffer.from(j.audio_base64, 'base64'));
    words[line.id] = toWords(j.alignment);
    const w = words[line.id];
    console.log(line.id, `${w.length} words, speech ${w[0][1]}-${w.at(-1)[2]}s`);
  }
  fs.writeFileSync(path.join(ROOT, 'assets/audio/words.js'),
    `// Generated by scripts/audio_gen.mjs — ElevenLabs word alignment per VO line: [text, start, end] seconds from the line's start.\n` +
    `(function (g) { g.HERCOVA_WORDS = ${JSON.stringify(words)}; })(typeof window !== 'undefined' ? window : globalThis);\n`);
}

